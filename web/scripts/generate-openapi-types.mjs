import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const source = process.env.SPRITE_STUDIO_OPENAPI_URL || 'http://127.0.0.1:8765/openapi.json'
const output = resolve(process.cwd(), 'src/api.generated.ts')
const response = await fetch(source)
if (!response.ok) throw new Error(`Unable to fetch OpenAPI document: ${response.status} ${response.statusText}`)
const document = await response.json()
const schemas = document.components?.schemas ?? {}

function typeOf(schema = {}) {
  if (schema.$ref) return schema.$ref.split('/').pop()
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (schema.oneOf) return schema.oneOf.map(typeOf).join(' | ')
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' | ')
  if (schema.type === 'array') return `${typeOf(schema.items)}[]`
  if (schema.type === 'object' || schema.properties) return 'Record<string, unknown>'
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  return 'string'
}

function renderInterface(name, schema) {
  const required = new Set(schema.required ?? [])
  const properties = Object.entries(schema.properties ?? {}).map(([key, value]) => {
    const safeKey = /^[$A-Z_][0-9A-Z_$]*$/i.test(key) ? key : JSON.stringify(key)
    return `  ${safeKey}${required.has(key) ? '' : '?'}: ${typeOf(value)};`
  })
  return `export interface ${name} {\n${properties.join('\n')}\n}`
}

const outputText = [
  '// Generated by scripts/generate-openapi-types.mjs — do not edit by hand.',
  `// Source: ${source}`,
  ...Object.entries(schemas).map(([name, schema]) => renderInterface(name, schema)),
  '',
  `export type ApiPath = ${Object.keys(document.paths ?? {}).map((path) => JSON.stringify(path)).join(' | ') || 'never'};`,
  '',
].join('\n\n')

await mkdir(dirname(output), { recursive: true })
await writeFile(output, outputText, 'utf8')
console.log(`Generated ${output}`)
